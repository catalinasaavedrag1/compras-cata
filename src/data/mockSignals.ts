/** Datos de apoyo coherentes con el maestro de productos (o explícitos si no hay SKU). */
function supportFor(
  sku: string,
  affectedStores: string[],
  stockoutEvents30 = 0,
  overrides: Partial<SignalSupport> = {}
): SignalSupport {
  const p = products.find((x) => x.sku === sku);
  return {
    stock: p?.availableStock ?? 0,
    sales30: p?.salesLast30Days ?? 0,
    rotation: p?.rotation ?? 0,
    marginPct: p?.margin ?? 0,
    stockoutEvents30,
    affectedStores,
    ...overrides,
  };
}

